export function publisherName(id: PublisherId) {
  return publishers.find((publisher) => publisher.id === id)?.name ?? id;
}

export function sortListings<T extends ShareListing>(listings: T[]) {
  return [...listings].sort((a, b) => {
    if (a.year !== b.year) {
      return b.year - a.year;
    }
    const publisherCompare = publisherName(a.publisherId).localeCompare(publisherName(b.publisherId));
    if (publisherCompare !== 0) {
      return publisherCompare;
    }
    const titleCompare = a.title.localeCompare(b.title);
    if (titleCompare !== 0) {
      return titleCompare;
    }
    return b.createdAt.localeCompare(a.createdAt);
  });
}
